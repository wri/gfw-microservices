/**
 * Returns the manual translation for the given text and language code.
 * Supports 'es' (Spanish) and 'pt' (Portuguese), with various locale formats (e.g. pt-BR, pt_BR).
 * Falls back to the original text if no translation is found.
 */
export const getManualTranslation = (text, languageCode) => {
  const translations = manualTranslations[text];
  if (!translations) {
    return text;
  }

  // Normalize language code - handle various formats like 'pt', 'pt-BR', 'pt_BR', 'pt-br'
  const normalizedCode = languageCode?.toLowerCase()?.split(/[-_]/)[0];

  if (normalizedCode === 'es') {
    return translations.es || text;
  }
  if (normalizedCode === 'pt') {
    return translations.pt || text;
  }

  return text;
};
